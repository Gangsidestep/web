<p class="faq-intro">Cette FAQ accompagne la <a class="blog-nav-link" href="<?php echo htmlspecialchars(localized_path('/theory-of-change/', $locale)); ?>">théorie du changement</a> développée par My Drop In The Oceans.</p>

