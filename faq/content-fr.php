  <h2 class="header_two">En une phrase</h2>
  <p>My Drop In The Oceans explore comment la valeur écologique peut devenir <strong>visible et partageable au point de transaction</strong>, afin que protéger la Nature devienne économiquement cohérent plutôt qu’exceptionnel sur le plan financier.</p>
