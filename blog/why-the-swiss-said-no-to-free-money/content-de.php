<h2 class="header_two" style="margin-top: 1.2em;">Bedingungsloses Grundeinkommen vs. Bürgerdividende für die Ökologie</h2>

<p>
  Das bedingungslose Grundeinkommen (BGE) wird typischerweise als bedingungsloses Einkommensnetz dargestellt — eine Grundzahlung, die Menschen unabhängig von ihrem Beschäftigungsstatus unterstützen soll.
  Eine ökologische Bürgerdividende unterscheidet sich in Zweck und Gestaltung: Sie basiert auf der Idee, dass <em>Naturkapital grundlegendes gemeinsames Vermögen ist</em>, und dass
  die aktuelle Wirtschaft es versäumt, ökologischen Wert auf die gleiche Weise finanziell sichtbar zu machen wie Produktivität (Löhne, Gewinne, Dividenden).
</p>

<p>
  Mit anderen Worten: Es geht nicht hauptsächlich darum, das Einkommen von der Arbeit zu entkoppeln. Es geht darum, Wertsignale zu korrigieren, damit Verantwortung mit den kurzfristigen Anreizen konkurrieren — und diese ergänzen — kann, die heute dominieren,
  und damit ökologischer Wert glaubwürdig, transparent und in großem Maßstab anerkannt werden kann. Für den größeren Rahmen siehe unsere
  <a class="blog-nav-link" href="<?php echo localized_url('/theory-of-change/', $locale ?? 'de'); ?>">Theorie des Wandels — Überblick</a>.
</p>

