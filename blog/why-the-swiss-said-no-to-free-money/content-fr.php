<h2 class="header_two" style="margin-top: 1.2em;">Revenu Universel de Base vs dividende écologique pour les citoyens</h2>

<p>
  Le Revenu Universel de Base (RUB) est généralement présenté comme un filet de sécurité de revenu inconditionnel — une allocation de base destinée à soutenir les personnes indépendamment de leur statut professionnel.
  Un dividende écologique pour les citoyens est différent dans son objectif et sa conception : il repose sur l\'idée que <em>le capital naturel est une richesse partagée fondamentale</em>, et que
  l\'économie actuelle ne rend pas la valeur écologique lisible financièrement de la même manière qu\'elle rend la productivité lisible (salaires, profits, dividendes).
</p>

<p>
  En d\'autres termes, ce n\'est pas principalement une question de découpler le revenu du travail. C\'est corriger les signaux de valeur pour que la gérance puisse concurrencer — et compléter —
  les incitations à court terme qui dominent aujourd\'hui, et pour que la valeur écologique soit reconnue de manière crédible, transparente et à grande échelle. Pour le cadre plus large, consultez notre
  <a class="blog-nav-link" href="<?php echo localized_url('/theory-of-change/', $locale ?? 'fr'); ?>">Théorie du changement — aperçu</a>.
</p>

