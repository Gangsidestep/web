<p>What a historic vote revealed about our emotional relationship with Nature, work, money, and worth.</p>

<p>
  Almost 10 years ago, in 2016, Switzerland held a world-first national referendum:
</p>

<blockquote>
  💬 Should all adults receive a Universal Basic Income (UBI)—unconditional, no strings attached?<br>
  💡 Everyone gets a basic allowance, no matter what you earn. No matter your job.
</blockquote>

<p>Result?<br>
❌ 76.9% voted no<br>
Even in one of the world's wealthiest, securest democracies, nearly 4 out of 5 people said: "Nope!"</p>

<p>So what really happened?<br>
It wasn't about inflation. Or budgets. Or laziness. It was about something deeper:</p>

<ul>
  <li>👉 A powerful emotional belief that money must be earned through work</li>
  <li>🧠 "You don't get something for nothing"</li>
  <li>💼 "Only work creates worth"</li>
  <li>💸 "No work = no pay"</li>
</ul>

<p>Even people who supported the idea felt uneasy. As if receiving money without producing something violated a deep inner contract. Switzerland just happened to put it to a vote.</p>

<p>But this isn't a Swiss story. 🌍 It's global.</p>

<p>So, here's the real question:<br>
💡 What about all the value we create for the planet that isn't paid?</p>

<ul>
  <li>🌍 Protecting Nature</li>
  <li>🚆 Choosing the train over the car</li>
  <li>🛒 Buying local and seasonal</li>
  <li>🏘️ Sharing resources instead of consuming more</li>
  <li>🔄 Repairing, reusing, recycling</li>
</ul>

<p>These are all acts of stewardship. They reduce harm. They restore balance. They bring long-term value for everyone.</p>

<p>But in today's economy?<br>
⚠️ They often count for nothing<br>
💥 Or worse—they're actively disincentivised</p>

<p>Why?<br>
Because a product or behaviour that harms people or the planet…<br>
…can still dominate in market value, while those that care, protect, or sustain don't.</p>

<p>🧾 In other words: the system rewards exploitation over stewardship.</p>

